// MARK: - Model & storage

struct ClipItem: Codable, Equatable {
    var text: String
    var date: Date
    var pinned: Bool = false
}

final class HistoryStore {
    static let maxItems = 300
    private(set) var items: [ClipItem] = []
    private let fileURL: URL?

    /// In-memory store (nothing read from or written to disk). Used for screenshots.
    init(demo: [ClipItem]) {
        fileURL = nil
        items = demo
    }

    init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipStack", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let url = dir.appendingPathComponent("history.json")
        fileURL = url
        if let data = try? Data(contentsOf: url),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    /// Pinned items first, then most recent first.
    var ordered: [ClipItem] { items.filter { $0.pinned } + items.filter { !$0.pinned } }

    func add(_ text: String) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        var pinned = false
        if let i = items.firstIndex(where: { $0.text == text }) {
            pinned = items[i].pinned
            items.remove(at: i)
        }
        items.insert(ClipItem(text: text, date: Date(), pinned: pinned), at: 0)
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= Self.maxItems
        }
        save()
    }

    func togglePin(_ text: String) {
        guard let i = items.firstIndex(where: { $0.text == text }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ text: String) {
        items.removeAll { $0.text == text }
        save()
    }

    func clearUnpinned() {
        items.removeAll { !$0.pinned }
        save()
    }

    private func save() {
        if let fileURL, let data = try? JSONEncoder().encode(items) {
            try? data.write(to: fileURL, options: .atomic)
        }
    }
}

// MARK: - Clipboard polling

final class ClipboardMonitor {
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    var onText: ((String) -> Void)?

    // Password managers mark secrets with these types; never record them.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = (pb.types ?? []).map(\.rawValue)
        if types.contains(where: ignoredTypes.contains) { return }
        if let s = pb.string(forType: .string) { onText?(s) }
    }
}

// MARK: - Global hotkey (Carbon; needs no special permission)

final class HotKey {
    private var hotKeyRef: EventHotKeyRef?
    private var handlerRef: EventHandlerRef?
    private let action: () -> Void

    init(keyCode: Int, modifiers: Int, action: @escaping () -> Void) {
        self.action = action
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        let me = Unmanaged.passUnretained(self).toOpaque()
        InstallEventHandler(GetApplicationEventTarget(), { _, _, userData in
            guard let userData else { return noErr }
            Unmanaged<HotKey>.fromOpaque(userData).takeUnretainedValue().action()
            return noErr
        }, 1, &spec, me, &handlerRef)
        let id = EventHotKeyID(signature: OSType(0x434C5354), id: 1) // 'CLST'
        RegisterEventHotKey(UInt32(keyCode), UInt32(modifiers), id, GetApplicationEventTarget(), 0, &hotKeyRef)
    }
}

// MARK: - Picker window

final class PickerPanel: NSPanel {
    var onCommandDigit: ((Int) -> Void)?
    override var canBecomeKey: Bool { true }

    override func performKeyEquivalent(with event: NSEvent) -> Bool {
        if event.modifierFlags.intersection(.deviceIndependentFlagsMask) == .command,
           let ch = event.charactersIgnoringModifiers, let n = Int(ch), (1...9).contains(n) {
            onCommandDigit?(n - 1)
            return true
        }
        return super.performKeyEquivalent(with: event)
    }
}

final class PickerController: NSObject, NSTableViewDataSource, NSTableViewDelegate, NSSearchFieldDelegate, NSWindowDelegate {
    private let store: HistoryStore
    private let panel: PickerPanel
    private let search = NSSearchField()
    private let table = NSTableView()
    private var rows: [ClipItem] = []
    var onPick: ((ClipItem) -> Void)?

    init(store: HistoryStore) {
        self.store = store
        panel = PickerPanel(contentRect: NSRect(x: 0, y: 0, width: 440, height: 480),
                            styleMask: [.nonactivatingPanel, .titled, .fullSizeContentView],
                            backing: .buffered, defer: false)
        super.init()

        panel.titleVisibility = .hidden
        panel.titlebarAppearsTransparent = true
        panel.isMovableByWindowBackground = true
        panel.level = .floating
        panel.hidesOnDeactivate = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        [.closeButton, .miniaturizeButton, .zoomButton].forEach { panel.standardWindowButton($0)?.isHidden = true }
        panel.delegate = self
        panel.onCommandDigit = { [weak self] i in self?.pick(row: i) }

        let bg = NSVisualEffectView()
        bg.material = .popover
        bg.state = .active
        panel.contentView = bg

        search.placeholderString = "Search clipboard history…"
        search.delegate = self
        search.focusRingType = .none
        search.translatesAutoresizingMaskIntoConstraints = false

        let column = NSTableColumn(identifier: .init("text"))
        table.addTableColumn(column)
        table.headerView = nil
        table.rowHeight = 26
        table.backgroundColor = .clear
        table.style = .inset
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.doubleAction = #selector(pickClicked)

        let menu = NSMenu()
        menu.addItem(withTitle: "Pin / Unpin", action: #selector(togglePinClicked), keyEquivalent: "").target = self
        menu.addItem(withTitle: "Delete", action: #selector(deleteClicked), keyEquivalent: "").target = self
        table.menu = menu

        let scroll = NSScrollView()
        scroll.documentView = table
        scroll.hasVerticalScroller = true
        scroll.drawsBackground = false
        scroll.translatesAutoresizingMaskIntoConstraints = false

        let hint = NSTextField(labelWithString: "↩ paste   ⌘1–9 quick paste   right-click to pin/delete   esc close")
        hint.font = .systemFont(ofSize: 10)
        hint.textColor = .secondaryLabelColor
        hint.translatesAutoresizingMaskIntoConstraints = false

        bg.addSubview(search)
        bg.addSubview(scroll)
        bg.addSubview(hint)
        NSLayoutConstraint.activate([
            search.topAnchor.constraint(equalTo: bg.topAnchor, constant: 30),
            search.leadingAnchor.constraint(equalTo: bg.leadingAnchor, constant: 12),
            search.trailingAnchor.constraint(equalTo: bg.trailingAnchor, constant: -12),
            scroll.topAnchor.constraint(equalTo: search.bottomAnchor, constant: 8),
            scroll.leadingAnchor.constraint(equalTo: bg.leadingAnchor),
            scroll.trailingAnchor.constraint(equalTo: bg.trailingAnchor),
            hint.topAnchor.constraint(equalTo: scroll.bottomAnchor, constant: 6),
            hint.centerXAnchor.constraint(equalTo: bg.centerXAnchor),
            hint.bottomAnchor.constraint(equalTo: bg.bottomAnchor, constant: -8),
        ])
    }

    var isVisible: Bool { panel.isVisible }

    /// Lays out the picker off-screen with the given search text and returns its content as an image.
    func snapshot(searchText: String, appearance: NSAppearance?) -> NSBitmapImageRep? {
        panel.appearance = appearance
        search.stringValue = searchText
        reload()
        guard let view = panel.contentView else { return nil }
        view.layoutSubtreeIfNeeded()
        guard let rep = view.bitmapImageRepForCachingDisplay(in: view.bounds) else { return nil }
        view.cacheDisplay(in: view.bounds, to: rep)
        return rep
    }

    /// The app that was in front when the picker opened; that's where we paste.
    private(set) var targetApp: NSRunningApplication?

    func show() {
        let front = NSWorkspace.shared.frontmostApplication
        targetApp = front?.processIdentifier == ProcessInfo.processInfo.processIdentifier ? nil : front
        search.stringValue = ""
        reload()
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { NSMouseInRect(mouse, $0.frame, false) } ?? NSScreen.main!
        let vf = screen.visibleFrame
        var origin = NSPoint(x: mouse.x - panel.frame.width / 2, y: mouse.y - panel.frame.height + 20)
        origin.x = min(max(origin.x, vf.minX + 8), vf.maxX - panel.frame.width - 8)
        origin.y = min(max(origin.y, vf.minY + 8), vf.maxY - panel.frame.height - 8)
        panel.setFrameOrigin(origin)
        panel.makeKeyAndOrderFront(nil)
        panel.makeFirstResponder(search)
    }

    func hide() { panel.orderOut(nil) }

    private func reload() {
        let q = search.stringValue.lowercased()
        rows = q.isEmpty ? store.ordered : store.ordered.filter { $0.text.lowercased().contains(q) }
        table.reloadData()
        if !rows.isEmpty { table.selectRowIndexes([0], byExtendingSelection: false); table.scrollRowToVisible(0) }
    }

    private func pick(row: Int) {
        guard rows.indices.contains(row) else { return }
        let item = rows[row]
        hide()
        onPick?(item)
    }

    /// Double-click: the table calls this while the second click is still being tracked, so
    /// finish the click first and wait until the mouse button is released before pasting.
    @objc private func pickClicked() {
        let row = table.clickedRow
        guard rows.indices.contains(row) else { return }
        log.info("double-click on row \(row, privacy: .public)")
        DispatchQueue.main.async { self.waitForMouseUp { self.pick(row: row) } }
    }

    private func waitForMouseUp(tries: Int = 50, then action: @escaping () -> Void) {
        if NSEvent.pressedMouseButtons == 0 || tries == 0 { action(); return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.02) {
            self.waitForMouseUp(tries: tries - 1, then: action)
        }
    }

    @objc private func togglePinClicked() {
        guard rows.indices.contains(table.clickedRow) else { return }
        store.togglePin(rows[table.clickedRow].text)
        reload()
    }

    @objc private func deleteClicked() {
        guard rows.indices.contains(table.clickedRow) else { return }
        store.remove(rows[table.clickedRow].text)
        reload()
    }

    // Table
    func numberOfRows(in tableView: NSTableView) -> Int { rows.count }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let item = rows[row]
        let oneLine = item.text.trimmingCharacters(in: .whitespacesAndNewlines)
            .replacingOccurrences(of: "\n", with: " ⏎ ")
        let prefix = row < 9 ? "\(row + 1)  " : "    "
        let label = NSTextField(labelWithString: prefix + (item.pinned ? "📌 " : "") + String(oneLine.prefix(300)))
        label.lineBreakMode = .byTruncatingTail
        label.maximumNumberOfLines = 1
        label.toolTip = String(item.text.prefix(1000))
        return label
    }

    // Keyboard handling inside the search field
    func controlTextDidChange(_ obj: Notification) { reload() }

    func control(_ control: NSControl, textView: NSTextView, doCommandBy sel: Selector) -> Bool {
        switch sel {
        case #selector(NSResponder.moveDown(_:)): moveSelection(1); return true
        case #selector(NSResponder.moveUp(_:)): moveSelection(-1); return true
        case #selector(NSResponder.insertNewline(_:)): pick(row: table.selectedRow); return true
        case #selector(NSResponder.cancelOperation(_:)): hide(); return true
        default: return false
        }
    }

    private func moveSelection(_ delta: Int) {
        guard !rows.isEmpty else { return }
        let next = min(max(table.selectedRow + delta, 0), rows.count - 1)
        table.selectRowIndexes([next], byExtendingSelection: false)
        table.scrollRowToVisible(next)
    }

    func windowDidResignKey(_ notification: Notification) { hide() }
}

// MARK: - App

final class AppDelegate: NSObject, NSApplicationDelegate, NSMenuDelegate {
    private var permissionItem: NSMenuItem!
    private var statusMenu: NSMenu!
    private var warnedAboutPermission = false
    private let store = HistoryStore()
    private let monitor = ClipboardMonitor()
    private var picker: PickerController!
    private var statusItem: NSStatusItem!
    private var hotKey: HotKey?
    private var loginItem: NSMenuItem!

    func applicationDidFinishLaunching(_ notification: Notification) {
        picker = PickerController(store: store)
        picker.onPick = { [weak self] item in self?.paste(item) }

        monitor.onText = { [weak self] text in self?.store.add(text) }
        monitor.start()

        hotKey = HotKey(keyCode: kVK_ANSI_V, modifiers: controlKey | cmdKey) { [weak self] in
            guard let self else { return }
            self.picker.isVisible ? self.picker.hide() : self.picker.show()
        }

        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        statusItem.button?.image = NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "ClipStack")
        let menu = NSMenu()
        menu.addItem(withTitle: "Show History  (⌃⌘V)", action: #selector(showPicker), keyEquivalent: "").target = self
        menu.addItem(.separator())
        loginItem = menu.addItem(withTitle: "Launch at Login", action: #selector(toggleLogin), keyEquivalent: "")
        loginItem.target = self
        loginItem.state = SMAppService.mainApp.status == .enabled ? .on : .off
        permissionItem = menu.addItem(withTitle: "", action: #selector(showPermissionHelp), keyEquivalent: "")
        permissionItem.target = self
        menu.addItem(withTitle: "Clear History (keeps pinned)", action: #selector(clearHistory), keyEquivalent: "").target = self
        menu.addItem(.separator())
        menu.addItem(withTitle: "About ClipStack", action: #selector(showAbout), keyEquivalent: "").target = self
        menu.addItem(withTitle: "ClipStack on GitHub", action: #selector(openGitHub), keyEquivalent: "").target = self
        menu.addItem(withTitle: "Quit ClipStack", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
        menu.delegate = self
        statusItem.menu = menu
        statusMenu = menu
        refreshPermissionItem()

        if !AXIsProcessTrusted() { askAccessibility() }
    }

    // Keep the menu accurate every time it opens.
    func menuWillOpen(_ menu: NSMenu) {
        refreshPermissionItem()
        loginItem.state = SMAppService.mainApp.status == .enabled ? .on : .off
    }

    /// Opening ClipStack again (Launchpad, Spotlight, Finder) while it's running shows its menu
    /// at the mouse pointer, so it's reachable even when the menu bar icon is hidden by the notch.
    func applicationShouldHandleReopen(_ sender: NSApplication, hasVisibleWindows flag: Bool) -> Bool {
        NSApp.activate(ignoringOtherApps: true)
        DispatchQueue.main.async {
            self.statusMenu.popUp(positioning: nil, at: NSEvent.mouseLocation, in: nil)
        }
        return false
    }

    private func refreshPermissionItem() {
        let ok = AXIsProcessTrusted()
        permissionItem.title = ok ? "Auto-paste: On" : "Auto-paste: Off — Fix…"
        permissionItem.state = ok ? .on : .off
    }

    private static let accessibilitySettingsURL =
        URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility")!

    /// Explains why pasting is off and how to fix it, including the stale-entry case.
    @objc private func showPermissionHelp() {
        if AXIsProcessTrusted() {
            NSWorkspace.shared.open(Self.accessibilitySettingsURL)
            return
        }
        askAccessibility() // registers ClipStack in the list if it isn't there yet
        let alert = NSAlert()
        alert.messageText = "ClipStack can copy, but can't paste for you yet"
        alert.informativeText = """
        To paste automatically, ClipStack needs Accessibility access.

        1. Open System Settings → Privacy & Security → Accessibility.
        2. If ClipStack is already listed (even if switched on), select it and click “–” to remove it. \
        An entry from an older version no longer matches this one.
        3. Click “+”, choose ClipStack in Applications, and switch it on.

        Until then, picking an item copies it and you can press ⌘V yourself.
        """
        alert.addButton(withTitle: "Open Accessibility Settings")
        alert.addButton(withTitle: "Later")
        NSApp.activate(ignoringOtherApps: true)
        if alert.runModal() == .alertFirstButtonReturn {
            NSWorkspace.shared.open(Self.accessibilitySettingsURL)
        }
    }

    @objc private func showPicker() { picker.show() }

    @objc private func showAbout() {
        let credits = NSAttributedString(
            string: "Clipboard history for macOS.\nPress ⌃⌘V anywhere.\n\(repoURL.absoluteString)",
            attributes: [.font: NSFont.systemFont(ofSize: 11), .foregroundColor: NSColor.secondaryLabelColor])
        NSApp.activate(ignoringOtherApps: true)
        NSApp.orderFrontStandardAboutPanel(options: [.credits: credits])
    }

    @objc private func openGitHub() { NSWorkspace.shared.open(repoURL) }

    @objc private func clearHistory() { store.clearUnpinned() }

    @objc private func askAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    @objc private func toggleLogin() {
        do {
            if SMAppService.mainApp.status == .enabled { try SMAppService.mainApp.unregister() }
            else { try SMAppService.mainApp.register() }
        } catch {
            NSAlert(error: error).runModal()
        }
        loginItem.state = SMAppService.mainApp.status == .enabled ? .on : .off
    }

    /// Put the item on the clipboard, then simulate ⌘V into the frontmost app.
    private func paste(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        let trusted = AXIsProcessTrusted()
        let target = picker.targetApp
        log.info("paste: trusted=\(trusted, privacy: .public) target=\(target?.bundleIdentifier ?? "none", privacy: .public)")
        guard trusted else {
            // Copied only. Explain once per launch instead of failing silently.
            if !warnedAboutPermission {
                warnedAboutPermission = true
                DispatchQueue.main.async { self.showPermissionHelp() }
            }
            return
        }
        // Make sure keyboard focus is back in the app we're pasting into. After a mouse click
        // on the picker it may not return there on its own.
        if let target, !target.isActive { target.activate(options: []) }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "none"
            log.info("sending ⌘V, frontmost=\(front, privacy: .public)")
            // A private source ignores keys the user may still be holding (e.g. ⌃ from ⌃⌘V),
            // so the target app receives exactly ⌘V.
            let src = CGEventSource(stateID: .privateState)
            let key = CGKeyCode(kVK_ANSI_V)
            let down = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: true)
            let up = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }
}

